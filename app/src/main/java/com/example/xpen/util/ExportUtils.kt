package com.example.xpen.util

import android.content.Context
import android.content.Intent
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.example.xpen.data.Expense
import java.io.File
import java.io.FileOutputStream

object ExportUtils {

    private fun getExportDir(context: Context): File {
        val dir = File(context.getExternalFilesDir(null), "Exports")
        if (!dir.exists()) dir.mkdirs()
        return dir
    }

    fun exportToCsv(context: Context, expenses: List<Expense>, fileLabel: String): File {
        val file = File(getExportDir(context), "Xpen_${fileLabel}_${System.currentTimeMillis()}.csv")
        file.bufferedWriter().use { writer ->
            writer.write("Date & Time,Amount,Category")
            writer.newLine()
            expenses.forEach { e ->
                writer.write("${DateUtils.formatDateTime(e.dateTime)},${CurrencyUtils.format(e.amount)},${e.category}")
                writer.newLine()
            }
        }
        return file
    }

    fun exportToPdf(context: Context, expenses: List<Expense>, fileLabel: String, title: String): File {
        val file = File(getExportDir(context), "Xpen_${fileLabel}_${System.currentTimeMillis()}.pdf")
        val pdfDocument = PdfDocument()
        val pageWidth = 595
        val pageHeight = 842
        val paint = Paint().apply { textSize = 12f }
        val titlePaint = Paint().apply { textSize = 18f; isFakeBoldText = true }
        val footerPaint = Paint().apply { textSize = 9f; color = android.graphics.Color.GRAY }
        val footerLinePaint = Paint().apply { color = android.graphics.Color.LTGRAY; strokeWidth = 1f }

        val logoBitmap = try {
            val original = android.graphics.BitmapFactory.decodeResource(
                context.resources, com.example.xpen.R.drawable.xpen_logo_transparent
            )
            val logoHeight = 22
            val logoWidth = (original.width * (logoHeight.toFloat() / original.height)).toInt()
            android.graphics.Bitmap.createScaledBitmap(original, logoWidth, logoHeight, true)
        } catch (e: Exception) { null }

        val footerBaseline = pageHeight - 30f
        val contentBottomLimit = pageHeight - 55

        fun drawFooter(canvas: android.graphics.Canvas) {
            canvas.drawLine(40f, footerBaseline - 12f, (pageWidth - 40).toFloat(), footerBaseline - 12f, footerLinePaint)
            var textX = 40f
            logoBitmap?.let {
                canvas.drawBitmap(it, 40f, footerBaseline - 8f, null)
                textX = 40f + it.width + 8f
            }
            canvas.drawText("Generated by Xpen", textX, footerBaseline + 6f, footerPaint)
        }

        var pageNumber = 1
        var page = pdfDocument.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create())
        var canvas = page.canvas
        var y = 40f

        canvas.drawText(title, 40f, y, titlePaint)
        y += 30f
        canvas.drawText("Date & Time", 40f, y, paint)
        canvas.drawText("Amount", 300f, y, paint)
        canvas.drawText("Category", 450f, y, paint)
        y += 20f

        expenses.forEach { e ->
            if (y > contentBottomLimit) {
                drawFooter(canvas)
                pdfDocument.finishPage(page)
                pageNumber++
                page = pdfDocument.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create())
                canvas = page.canvas
                y = 40f
            }
            canvas.drawText(DateUtils.formatDateTime(e.dateTime), 40f, y, paint)
            canvas.drawText(CurrencyUtils.format(e.amount), 300f, y, paint)
            canvas.drawText(e.category, 450f, y, paint)
            y += 20f
        }
        drawFooter(canvas)
        pdfDocument.finishPage(page)

        FileOutputStream(file).use { out -> pdfDocument.writeTo(out) }
        pdfDocument.close()
        return file
    }

    fun shareFile(context: Context, file: File, mimeType: String) {
        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(intent, "Share export"))
    }
}